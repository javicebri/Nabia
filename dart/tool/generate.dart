/// Source of `providers/<name>.g.dart`: endpoints, constants, tables.
String providerSource(Map<String, Object?> document) {
  _checkVersion(document);
  final provider = _string(document, 'provider');
  final className = '${_pascal(provider)}Contract';
  final members = <String, String>{};

  void add(String key, String declaration) {
    final name = _identifier(key);
    if (members.containsKey(name) || name == 'provider') {
      throw FormatException('$provider: duplicate member $name');
    }
    members[name] = declaration;
  }

  for (final MapEntry(:key, :value) in _map(document, 'endpoints').entries) {
    add(
      key,
      '  /// Default endpoint `$key`.\n'
      '  static const ${_identifier(key)} = ${_literal(value! as String)};',
    );
  }
  for (final MapEntry(:key, :value) in _map(document, 'constants').entries) {
    add(
      key,
      '  /// Constant `${key.toUpperCase()}` of the provider mapping.\n'
      '  static const ${_identifier(key)} = ${_constant(value)};',
    );
  }
  for (final MapEntry(:key, :value) in _map(document, 'datasets').entries) {
    final table = value! as Map<String, Object?>;
    final out = StringBuffer()
      ..writeln('  /// Equivalence table of dataset `$key`.')
      ..writeln('  static const ${_identifier(key)} = VariableTable(')
      ..writeln('    provider: ${_literal(provider)},')
      ..writeln('    dataset: ${_literal(key)},')
      ..writeln(
        '    referenceUrl: ${_literal(_string(table, 'reference_url'))},',
      )
      ..writeln('    verifiedOn: ${_literal(_string(table, 'verified_on'))},');
    for (final resolution in ['hourly', 'daily']) {
      out.writeln('    $resolution: {');
      for (final MapEntry(key: variable, :value) in _map(
        table,
        resolution,
      ).entries) {
        final native = value! as Map<String, Object?>;
        out
          ..writeln('      Variable.${_identifier(variable)}: NativeVariable(')
          ..writeln('        name: ${_literal(_string(native, 'name'))},')
          ..writeln(
            '        unit: Unit.${_identifier(_string(native, 'unit'))},',
          )
          ..writeln('        notes: ${_literal(_string(native, 'notes'))},')
          ..writeln('      ),');
      }
      out.writeln('    },');
    }
    out.write('  );');
    add(key, out.toString());
  }

  final buffer = StringBuffer(_header)
    ..writeln("import '../../catalog/table.dart';")
    ..writeln("import '../catalog.g.dart';")
    ..writeln()
    ..writeln('/// Contract of provider `$provider`, from its `mapping.py`')
    ..writeln('/// and default settings in the Python reference.')
    ..writeln('abstract final class $className {')
    ..writeln('  /// Provider identifier used in output and errors.')
    ..writeln('  static const provider = ${_literal(provider)};');
  for (final declaration in members.values) {
    buffer
      ..writeln()
      ..writeln(declaration);
  }
  buffer.writeln('}');
  return buffer.toString();
}

/// Dart constant expression for a JSON value, with explicit types.
String _constant(Object? value) {
  return switch (value) {
    null => 'null',
    bool() || int() => '$value',
    double() => _doubleLiteral(value),
    String() => _literal(value),
    List<Object?>() =>
      '<${_valueType(value)}>[${value.map(_constant).join(', ')}]',
    Map<String, Object?>() =>
      '<String, ${_valueType(value.values)}>{'
          '${value.entries.map((e) => '${_literal(e.key)}: ${_constant(e.value)}').join(', ')}}',
    _ => throw FormatException('No Dart form for $value'),
  };
}

String _valueType(Iterable<Object?> values) {
  final types = values.map(_scalarType).toSet();
  return types.length == 1 ? types.single : 'Object?';
}

String _scalarType(Object? value) => switch (value) {
  null => 'Null',
  bool() => 'bool',
  int() => 'int',
  double() => 'double',
  String() => 'String',
  List<Object?>() => 'List<${_valueType(value)}>',
  Map<String, Object?>() => 'Map<String, ${_valueType(value.values)}>',
  _ => throw FormatException('No Dart type for $value'),
};

// -- helpers ---------------------------------------------------------------

Future<Map<String, String>> _format(Map<String, String> sources) async {
  final temp = Directory.systemTemp.createTempSync('nabia_generate_');
  try {
    for (final MapEntry(:key, :value) in sources.entries) {
      File('${temp.path}/$key')
        ..parent.createSync(recursive: true)
        ..writeAsStringSync(value);
    }
    final result = await Process.run(Platform.resolvedExecutable, [
      'format',
      '--language-version=3.10',
      temp.path,
    ]);
    if (result.exitCode != 0) {
      throw StateError('dart format failed: ${result.stderr}');
    }
    return {
      for (final key in sources.keys)
        key: File('${temp.path}/$key').readAsStringSync(),
    };
  } finally {
    temp.deleteSync(recursive: true);
  }
}

Map<String, Object?> _readJson(File file) =>
    jsonDecode(file.readAsStringSync()) as Map<String, Object?>;

void _checkVersion(Map<String, Object?> document) {
  final version = document['contract_version'];
  if (version != supportedContractVersion) {
    throw FormatException(
      'Contract version $version is not supported '
      '(expected $supportedContractVersion): update tool/generate.dart',
    );
  }
}

String _string(Map<String, Object?> map, String key) => map[key]! as String;

double _double(Map<String, Object?> map, String key) =>
    (map[key]! as num).toDouble();

List<Object?> _list(Map<String, Object?> map, String key) =>
    map[key]! as List<Object?>;

List<String> _strings(Map<String, Object?> map, String key) =>
    _list(map, key).cast<String>();

Map<String, Object?> _map(Map<String, Object?> map, String key) =>
    map[key]! as Map<String, Object?>;

/// `snake_case` to a lowerCamelCase identifier, rejecting keywords.
String _identifier(String snake) {
  final parts = snake.split('_');
  final name =
      parts.first +
      parts.skip(1).map((p) => p.isEmpty ? p : _capital(p)).join();
  if (!RegExp(r'^[a-z][a-zA-Z0-9]*$').hasMatch(name) ||
      _reserved.contains(name)) {
    throw FormatException('Cannot derive a Dart identifier from "$snake"');
  }
  return name;
}

String _pascal(String snake) => _capital(_identifier(snake));

String _capital(String text) => text[0].toUpperCase() + text.substring(1);

/// Single-quoted Dart string literal with escapes.
String _literal(String text) {
  final escaped = text
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n');
  return "'$escaped'";
}

String _doubleLiteral(double value) {
  if (!value.isFinite) throw FormatException('Non-finite number: $value');
  final text = value.toString();
  return text.contains('.') || text.contains('e') ? text : '$text.0';
}

void _docComment(StringBuffer buffer, String text, {required String indent}) {
  const width = 72;
  var line = '';
  for (final word in text.split(RegExp(r'\s+'))) {
    if (line.isNotEmpty && line.length + word.length + 1 > width) {
      buffer.writeln('$indent/// $line');
      line = word;
    } else {
      line = line.isEmpty ? word : '$line $word';
    }
  }
  if (line.isNotEmpty) buffer.writeln('$indent/// $line');
}
