/// Source of `catalog.g.dart`: units, enums, variables, conversions.
String catalogSource(Map<String, Object?> document) {
  _checkVersion(document);
  final units = _map(document, 'units');
  final buffer = StringBuffer(_header)
    ..writeln("import '../catalog/conversion.dart';")
    ..writeln()
    ..writeln('/// Physical units; [symbol] is the text used in output.')
    ..writeln('enum Unit {');
  final unitKeys = units.keys.toList();
  for (final (index, key) in unitKeys.indexed) {
    final symbol = units[key]! as String;
    buffer
      ..writeln('  /// `$symbol`')
      ..write('  ${_identifier(key)}(${_literal(symbol)})')
      ..writeln(index == unitKeys.length - 1 ? ';' : ',');
  }
  buffer
    ..writeln()
    ..writeln('  const Unit(this.symbol);')
    ..writeln()
    ..writeln('  /// Symbol used in output.')
    ..writeln('  final String symbol;')
    ..writeln()
    ..writeln('  /// The unit whose [symbol] is [symbol].')
    ..writeln('  ///')
    ..writeln('  /// Throws an [ArgumentError] for unknown symbols.')
    ..writeln('  static Unit fromSymbol(String symbol) =>')
    ..writeln('      _bySymbol[symbol] ??')
    ..writeln(
      "      (throw ArgumentError.value(symbol, 'symbol', 'Unknown unit'));",
    )
    ..writeln()
    ..writeln(
      '  static final _bySymbol = {for (final u in values) u.symbol: u};',
    )
    ..writeln('}')
    ..writeln();

  _keyedEnum(
    buffer,
    'Resolution',
    'Temporal resolution of a series.',
    _strings(document, 'resolutions'),
  );
  _keyedEnum(
    buffer,
    'Aggregation',
    'How a value relates to its time interval.',
    _strings(document, 'aggregations'),
  );
  _keyedEnum(
    buffer,
    'SourceKind',
    'Nature of the data in a series; only `observation` is a direct '
        'measurement.',
    _strings(document, 'source_kinds'),
  );

  final variables = _map(document, 'variables');
  buffer
    ..writeln('/// Canonical variables; [key] is the name used in output.')
    ..writeln('enum Variable {');
  final variableKeys = variables.keys.toList();
  for (final (index, key) in variableKeys.indexed) {
    final spec = variables[key]! as Map<String, Object?>;
    final description = _string(spec, 'description');
    final resolutions = _strings(
      spec,
      'resolutions',
    ).map((r) => 'Resolution.${_identifier(r)}').join(', ');
    _docComment(buffer, description, indent: '  ');
    buffer
      ..writeln('  ${_identifier(key)}(')
      ..writeln('    ${_literal(key)},')
      ..writeln('    Unit.${_identifier(_string(spec, 'unit'))},')
      ..writeln('    Aggregation.${_identifier(_string(spec, 'aggregation'))},')
      ..writeln('    {$resolutions},')
      ..writeln('    ${_literal(description)},')
      ..writeln(index == variableKeys.length - 1 ? '  );' : '  ),');
  }
  buffer
    ..writeln()
    ..writeln('  const Variable(')
    ..writeln('    this.key,')
    ..writeln('    this.unit,')
    ..writeln('    this.aggregation,')
    ..writeln('    this.resolutions,')
    ..writeln('    this.description,')
    ..writeln('  );')
    ..writeln()
    ..writeln('  /// Name used in output and in the contract.')
    ..writeln('  final String key;')
    ..writeln()
    ..writeln('  /// Canonical unit of every value.')
    ..writeln('  final Unit unit;')
    ..writeln()
    ..writeln('  /// How each value relates to its time interval.')
    ..writeln('  final Aggregation aggregation;')
    ..writeln()
    ..writeln('  /// Resolutions the variable is defined for.')
    ..writeln('  final Set<Resolution> resolutions;')
    ..writeln()
    ..writeln('  /// Precise definition.')
    ..writeln('  final String description;')
    ..writeln()
    ..writeln('  /// The variable whose [key] is [key].')
    ..writeln('  ///')
    ..writeln('  /// Throws an [ArgumentError] for unknown keys.')
    ..writeln('  static Variable fromKey(String key) =>')
    ..writeln('      _byKey[key] ??')
    ..writeln(
      "      (throw ArgumentError.value(key, 'key', 'Unknown variable'));",
    )
    ..writeln()
    ..writeln('  static final _byKey = {for (final v in values) v.key: v};')
    ..writeln('}')
    ..writeln()
    ..writeln(
      '/// Conversion from [source] to [target], or `null` if undefined.',
    )
    ..writeln('///')
    ..writeln('/// Identity is not listed: equal units need no conversion.')
    ..writeln('Conversion? conversionBetween(Unit source, Unit target) =>')
    ..writeln('    switch ((source, target)) {');
  for (final entry in _list(document, 'conversions')) {
    final conversion = entry! as Map<String, Object?>;
    final from = _identifier(_string(conversion, 'from'));
    final to = _identifier(_string(conversion, 'to'));
    if (!units.containsKey(conversion['from']) ||
        !units.containsKey(conversion['to'])) {
      throw FormatException('Conversion between unknown units: $conversion');
    }
    buffer
      ..writeln('      (Unit.$from, Unit.$to) => const Conversion(')
      ..writeln(
        '        offset: ${_doubleLiteral(_double(conversion, 'offset'))},',
      )
      ..writeln(
        '        divisor: ${_doubleLiteral(_double(conversion, 'divisor'))},',
      )
      ..writeln('      ),');
  }
  buffer
    ..writeln('      _ => null,')
    ..writeln('    };');
  return buffer.toString();
}

void _keyedEnum(
  StringBuffer buffer,
  String name,
  String doc,
  List<String> keys,
) {
  buffer.writeln('/// $doc');
  buffer.writeln('enum $name {');
  for (final (index, key) in keys.indexed) {
    buffer
      ..writeln('  /// `$key`')
      ..write('  ${_identifier(key)}(${_literal(key)})')
      ..writeln(index == keys.length - 1 ? ';' : ',');
  }
  buffer
    ..writeln()
    ..writeln('  const $name(this.key);')
    ..writeln()
    ..writeln('  /// Value used in output and in the contract.')
    ..writeln('  final String key;')
    ..writeln()
    ..writeln('  /// The member whose [key] is [key].')
    ..writeln('  ///')
    ..writeln('  /// Throws an [ArgumentError] for unknown keys.')
    ..writeln('  static $name fromKey(String key) =>')
    ..writeln('      _byKey[key] ??')
    ..writeln("      (throw ArgumentError.value(key, 'key', 'Unknown $name'));")
    ..writeln()
    ..writeln('  static final _byKey = {for (final m in values) m.key: m};')
    ..writeln('}')
    ..writeln();
}

