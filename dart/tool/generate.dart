/// Generates Dart sources from the shared contract (`../contract`).
///
/// Python is the reference implementation and exports the contract;
/// this package never copies Python code, it generates its vocabulary
/// and provider tables from the contract instead. Run from `dart/`:
///
///     dart run tool/generate.dart          # regenerate
///     dart run tool/generate.dart --check  # exit 1 if stale
library;

import 'dart:convert';
import 'dart:io';

/// Contract structure version this generator understands.
const supportedContractVersion = 1;

/// Directory of the generated sources, relative to the package root.
const generatedDir = 'lib/src/generated';

const _header =
    '// GENERATED by tool/generate.dart from contract/ - do not edit.\n'
    '// Regenerate with: dart run tool/generate.dart\n\n';

const _reserved = {
  'assert', 'break', 'case', 'catch', 'class', 'const', 'continue', //
  'default', 'do', 'else', 'enum', 'extends', 'false', 'final', //
  'finally', 'for', 'if', 'in', 'is', 'new', 'null', 'rethrow', //
  'return', 'super', 'switch', 'this', 'throw', 'true', 'try', 'var', //
  'void', 'while', 'with', 'values', 'index', 'name', 'key', //
};

/// Regenerates [generatedDir], or checks it with `--check`.
Future<void> main(List<String> args) async {
  final check = args.contains('--check');
  if (args.any((arg) => arg != '--check')) {
    stderr.writeln('usage: dart run tool/generate.dart [--check]');
    exitCode = 64;
    return;
  }
  final sources = await generateSources(Directory('../contract'));
  final outdated = staleFiles(Directory(generatedDir), sources);
  if (check) {
    if (outdated.isNotEmpty) {
      stderr
        ..writeln('$generatedDir is stale: ${outdated.join(', ')}')
        ..writeln('Run: dart run tool/generate.dart');
      exitCode = 1;
    }
    return;
  }
  for (final name in outdated) {
    final file = File('$generatedDir/$name');
    final content = sources[name];
    if (content == null) {
      file.deleteSync();
    } else {
      file.parent.createSync(recursive: true);
      file.writeAsStringSync(content);
    }
    stdout.writeln('$generatedDir/$name');
  }
}

/// Returns every generated file (path relative to [generatedDir]) with
/// its formatted content.
Future<Map<String, String>> generateSources(Directory contract) async {
  final sources = <String, String>{
    'catalog.g.dart': catalogSource(
      _readJson(File('${contract.path}/catalog.json')),
    ),
  };
  final providers =
      Directory('${contract.path}/providers')
          .listSync()
          .whereType<File>()
          .where((file) => file.path.endsWith('.json'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  for (final file in providers) {
    final document = _readJson(file);
    final provider = _string(document, 'provider');
    sources['providers/$provider.g.dart'] = providerSource(document);
  }
  return _format(sources);
}

/// Returns the generated files that are outdated, missing or extra.
List<String> staleFiles(Directory directory, Map<String, String> sources) {
  final existing = <String, String>{};
  if (directory.existsSync()) {
    for (final file in directory.listSync(recursive: true).whereType<File>()) {
      final name = file.path
          .substring(directory.path.length + 1)
          .replaceAll(r'\', '/');
      existing[name] = file.readAsStringSync();
    }
  }
  final names = {...existing.keys, ...sources.keys}.toList()..sort();
  return [
    for (final name in names)
      if (existing[name] != sources[name]) name,
  ];
}

